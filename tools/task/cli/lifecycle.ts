interface AutoGeneratedFileItem {
  wtPath: string;
  repo: RuntimeRepo;
  file: string;
  xy: string;
}

function formatStartRejection(check: Extract<EvaluateStartResult, { ok: false }>): string {
  if (check.reasonCode === 'broad-scope' && Array.isArray(check.violations) && check.violations.length > 0) {
    return `拒絕開工：影響範圍太寬：\n${check.violations.map((v) => `- ${v.raw}：${v.reason}`).join('\n')}`;
  }
  return `拒絕開工：${check.reason}`;
}

function validateStartPreconditions(
  ctx: TaskContext,
  { issueNum, taskDir, branchName }: { issueNum: number; taskDir: string; branchName: string },
): { check: Extract<EvaluateStartResult, { ok: true }>; affectedRepos: Set<string> } {
  const issues = fetchAllIssues(ctx);
  const target = issues.find((it) => it.number === issueNum) || null;
  const needComments = Boolean(target && target.state === 'open' && getLabelNames(target).includes('status:ready'));
  const comments = needComments ? fetchIssueComments(ctx, issueNum) : [];

  const check = ctx.lib.evaluateIssueCanStart(target, {
    issueNum,
    issuesLookup: issues,
    activeIssues: issues,
    comments,
    requireDispatch: true,
    requireScope: true,
  });
  if (!check.ok) fail(formatStartRejection(check));

  const affectedRepos = getAffectedRepoKeys(check.scope);
  preflightLocalWorktreeBuild(ctx, { taskDir, branchName, affectedRepos, actionLabel: '開工' });
  return { check, affectedRepos };
}

export async function cmdStart(
  ctx: TaskContext,
  { issueNum, worker, dryRun = false }: Pick<IssueCommandArgs, 'issueNum' | 'worker'> & { dryRun?: boolean },
): Promise<number> {
  const taskDir = getTaskDir(ctx, issueNum);
  const branchName = formatTaskBranch(ctx, issueNum);

  if (dryRun) {
    const { affectedRepos } = validateStartPreconditions(ctx, { issueNum, taskDir, branchName });
    console.log(`[dry-run] 檢查通過，預計建立工作資料夾：${taskDir}`);
    for (const repo of ctx.repos) {
      const wtPath = path.join(taskDir, repo.name);
      const targetRef = affectedRepos.has(repo.key) ? branchName : `${resolveBaseRef(repo.mainRepoPath)} (detached)`;
      console.log(`- ${repo.name} (${repo.key}): ${wtPath} -> ${targetRef}`);
    }
    return 0;
  }

  const lockDir = path.join(ctx.worktreeRoot, '.task-start.lock');
  await acquireDirLock(lockDir, { issueNum, action: 'start' }, { rejectLabel: '開工鎖' });

  try {
    const { affectedRepos } = validateStartPreconditions(ctx, { issueNum, taskDir, branchName });
    const branchSummaryLines = claimLabelsAndBuildWorktrees(ctx, {
      issueNum,
      worker,
      taskDir,
      branchName,
      affectedRepos,
      addLabel: 'status:in-progress',
      removeLabel: 'status:ready',
      actionLabel: '開工',
    });

    const commentBody = [
      `🛠️ ${worker}`,
      '🔁 接手',
      '',
      `已建立任務工作資料夾：\`${taskDir}\``,
      '',
      '各倉庫分支：',
      ...branchSummaryLines,
    ].join('\n');
    postIssueComment(ctx, issueNum, commentBody);
    await recordWorkerClaim(ctx, { worker, issueNum });

    console.log(`開工完成：${taskDir}`);
    return 0;
  } finally {
    releaseDirLock(lockDir);
  }
}

type ResumeMode =
  | { kind: 'rework' }
  | { kind: 'takeover'; prevWorker: string; prevRole: WorkerRole; prevHeartbeatAt: string };

function reuseExistingTaskDir(
  ctx: TaskContext,
  {
    issueNum,
    worker,
    taskDir,
    branchName,
    affectedRepos,
    isRework,
  }: {
    issueNum: number;
    worker: string;
    taskDir: string;
    branchName: string;
    affectedRepos: ReadonlySet<string>;
    isRework: boolean;
  },
): string[] {
  if (isRework) {
    swapIssueLabels(ctx, issueNum, 'status:in-progress', 'status:rework');
  }
  const summaryLines = [`沿用既有任務資料夾：\`${taskDir}\``];
  try {
    for (const repo of ctx.repos) {
      if (!affectedRepos.has(repo.key)) continue;
      const wtPath = path.join(taskDir, repo.name);
      if (!fs.existsSync(wtPath)) continue;
      const fetchRes = runGit(wtPath, ['fetch', 'origin']);
      if (!fetchRes.ok) {
        fail(`拒絕接手：${repo.name} 執行 git fetch 失敗：${fetchRes.stderr || fetchRes.stdout}`);
      }
      const hasRemote = runGit(wtPath, ['rev-parse', '--verify', '-q', `refs/remotes/origin/${branchName}`]).ok;
      if (hasRemote) {
        const ahead = runGit(wtPath, ['rev-list', '--count', `origin/${branchName}..HEAD`]);
        const countText = ahead.ok ? ahead.stdout.trim() : '?';
        summaryLines.push(`- \`${repo.name}\`（\`${repo.key}\`）：沿用 \`${branchName}\`（本機比遠端多 ${countText} 個提交）`);
      } else {
        summaryLines.push(`- \`${repo.name}\`（\`${repo.key}\`）：沿用 \`${branchName}\`（尚未推送到遠端）`);
      }
    }
    return summaryLines;
  } catch (err: unknown) {
    if (isRework) {
      try { removeIssueLabel(ctx, issueNum, 'status:in-progress'); } catch {}
      try { addIssueLabel(ctx, issueNum, 'status:rework'); } catch {}
      try {
        const reason = err instanceof Error ? err.message : String(err);
        postIssueComment(ctx, issueNum, `🛠️ ${worker}\n接手重修失敗，已還原標籤為 \`status:rework\`：\n\n${reason}`);
      } catch {}
    }
    throw err;
  }
}

/**
 * 交接接手且本機無任務資料夾時，依「遠端任務分支優先、無則 origin/main」重建 worktree，全程不改動 GitHub 標籤。
 * @why `claimLabelsAndBuildWorktrees` 會交換狀態標籤；接手進行中的單須維持 `status:in-progress`，故僅於此執行無標籤改動的重建與失敗清理。
 */
function buildTakeoverWorktrees(
  ctx: TaskContext,
  {
    taskDir,
    branchName,
    affectedRepos,
  }: { taskDir: string; branchName: string; affectedRepos: ReadonlySet<string> },
): string[] {
  let createdTaskDir = false;
  const createdWorktrees: Array<{ mainRepoPath: string; wtPath: string }> = [];
  const createdBranches: Array<{ mainRepoPath: string; branch: string }> = [];
  const branchSummaryLines: string[] = [];

  try {
    for (const repo of ctx.repos) {
      const fetchRes = runGit(repo.mainRepoPath, ['fetch', 'origin']);
      if (!fetchRes.ok) {
        fail(`拒絕接手：${repo.name} 執行 git fetch 失敗：${fetchRes.stderr || fetchRes.stdout}`);
      }
    }

    const startPoints = new Map<string, string>();
    const preExistingLocalBranches = new Set<string>();
    for (const repo of ctx.repos) {
      if (!affectedRepos.has(repo.key)) continue;
      const hasRemoteBranch = runGit(repo.mainRepoPath, [
        'rev-parse',
        '--verify',
        '-q',
        `refs/remotes/origin/${branchName}`,
      ]).ok;
      const startPoint = hasRemoteBranch ? `origin/${branchName}` : resolveBaseRef(repo.mainRepoPath);
      startPoints.set(repo.key, startPoint);
      if (checkLocalUnpushedBranch(repo.mainRepoPath, repo.name, branchName, startPoint, '接手')) {
        preExistingLocalBranches.add(repo.key);
      }
    }

    fs.mkdirSync(taskDir);
    createdTaskDir = true;

    for (const repo of ctx.repos) {
      const wtPath = path.join(taskDir, repo.name);
      runGit(repo.mainRepoPath, ['worktree', 'prune']);
      if (affectedRepos.has(repo.key)) {
        const startPoint = startPoints.get(repo.key) || resolveBaseRef(repo.mainRepoPath);
        const addRes = runGit(repo.mainRepoPath, ['worktree', 'add', '-B', branchName, wtPath, startPoint]);
        if (!addRes.ok) {
          fail(`建立 ${repo.name} worktree 失敗：${addRes.stderr || addRes.stdout}`);
        }
        createdWorktrees.push({ mainRepoPath: repo.mainRepoPath, wtPath });
        if (!preExistingLocalBranches.has(repo.key)) {
          createdBranches.push({ mainRepoPath: repo.mainRepoPath, branch: branchName });
        }
        branchSummaryLines.push(`- \`${repo.name}\`（\`${repo.key}\`）：\`${branchName}\`（起點：\`${startPoint}\`）`);
      } else {
        const baseRef = resolveBaseRef(repo.mainRepoPath);
        const addRes = runGit(repo.mainRepoPath, ['worktree', 'add', '--detach', wtPath, baseRef]);
        if (!addRes.ok) {
          fail(`建立 ${repo.name} detached worktree 失敗：${addRes.stderr || addRes.stdout}`);
        }
        createdWorktrees.push({ mainRepoPath: repo.mainRepoPath, wtPath });
        branchSummaryLines.push(`- \`${repo.name}\`（\`${repo.key}\`）：\`${baseRef}\` (detached)`);
      }
    }
    return branchSummaryLines;
  } catch (err: unknown) {
    for (const { mainRepoPath, wtPath } of createdWorktrees) {
      runGit(mainRepoPath, ['worktree', 'remove', '--force', wtPath]);
      runGit(mainRepoPath, ['worktree', 'prune']);
    }
    for (const { mainRepoPath, branch } of createdBranches) {
      runGit(mainRepoPath, ['branch', '-D', branch]);
    }
    if (createdTaskDir) {
      fs.rmSync(taskDir, { recursive: true, force: true });
    }
    throw err;
  }
}

export async function cmdResume(
  ctx: TaskContext,
  { issueNum, worker }: Pick<IssueCommandArgs, 'issueNum' | 'worker'>,
): Promise<number> {
  const limits = loadWorkerLimits(ctx.config);
  const taskDir = getTaskDir(ctx, issueNum);
  const branchName = formatTaskBranch(ctx, issueNum);
  const lockDir = path.join(ctx.worktreeRoot, '.task-start.lock');
  await acquireDirLock(lockDir, { issueNum, action: 'resume' }, { rejectLabel: '開工鎖' });

  try {
    const target = fetchSingleIssue(ctx, issueNum);
    if (!target) fail(`拒絕接手：找不到 issue #${issueNum}`);
    if (target.state !== 'open') fail(`拒絕接手：issue #${issueNum} 已關閉`);

    const labels = getLabelNames(target);
    let mode: ResumeMode;
    if (labels.includes('status:rework')) {
      // 手動重修不必受限於新對話寬限期，傳入已過寬限時間的基準留言供狀態與開關檢查
      const check = ctx.lib.evaluateIssueCanResume(target, {
        comments: [{ body: '🤖 Claude', created_at: '1970-01-01T00:00:00Z' }],
      });
      if (!check.ok) fail(`拒絕接手：${check.reason}`);
      mode = { kind: 'rework' };
    } else if (labels.includes('status:in-progress') && !labels.includes('status:fixed')) {
      const takeover = evaluateTicketTakeover(ctx.worktreeRoot, target, worker, limits);
      if (!takeover.ok) fail(`拒絕接手：${takeover.reason}`);
      mode = {
        kind: 'takeover',
        prevWorker: takeover.prevWorker,
        prevRole: takeover.prevRole,
        prevHeartbeatAt: takeover.prevHeartbeatAt,
      };
    } else {
      fail(`拒絕接手：issue #${issueNum} 沒有 status:rework 標籤，也不是可接手的進行中單`);
    }

    const scope = parseValidatedScope(ctx.lib, issueNum, target.body, '拒絕接手');
    const affectedRepos = getAffectedRepoKeys(scope);
    let summaryLines: string[];

    if (fs.existsSync(taskDir)) {
      summaryLines = reuseExistingTaskDir(ctx, {
        issueNum,
        worker,
        taskDir,
        branchName,
        affectedRepos,
        isRework: mode.kind === 'rework',
      });
    } else {
      preflightLocalWorktreeBuild(ctx, { taskDir, branchName, affectedRepos, actionLabel: '接手' });
      const branchSummaryLines =
        mode.kind === 'rework'
          ? claimLabelsAndBuildWorktrees(ctx, {
              issueNum,
              worker,
              taskDir,
              branchName,
              affectedRepos,
              addLabel: 'status:in-progress',
              removeLabel: 'status:rework',
              actionLabel: '接手',
            })
          : buildTakeoverWorktrees(ctx, { taskDir, branchName, affectedRepos });
      summaryLines = [`原本的任務資料夾不在，已重建：\`${taskDir}\``, ...branchSummaryLines];
    }

    const commentBody =
      mode.kind === 'takeover'
        ? [
            `🛠️ ${worker}`,
            `🔁 接手（交接自 ${mode.prevWorker}）`,
            '',
            `前一位協調者：${mode.prevWorker}（${
              mode.prevRole === 'retired' ? '已退休，' : ''
            }最後心跳 ${mode.prevHeartbeatAt}）`,
            '',
            ...summaryLines,
          ].join('\n')
        : [`🛠️ ${worker}`, '🔁 接手重修', '', ...summaryLines].join('\n');
    postIssueComment(ctx, issueNum, commentBody);
    await recordWorkerClaim(ctx, { worker, issueNum });

    console.log(`接手完成：${taskDir}`);
    return 0;
  } finally {
    releaseDirLock(lockDir);
  }
}

export async function cmdSubmit(
  ctx: TaskContext,
  { issueNum, worker, note = '' }: Pick<IssueCommandArgs, 'issueNum' | 'worker'> & { note?: string },
): Promise<number> {
  const target = fetchSingleIssue(ctx, issueNum);
  if (!target) fail(`拒絕交件：找不到 issue #${issueNum}`);
  if (target.state !== 'open') fail(`拒絕交件：issue #${issueNum} 已關閉`);
  const labels = getLabelNames(target);
  if (!labels.includes('status:in-progress')) {
    fail(`拒絕交件：issue #${issueNum} 沒有 status:in-progress 標籤`);
  }

  if (labels.includes('kind:no-commit')) {
    const trimmedNote = typeof note === 'string' ? note.trim() : '';
    if (!trimmedNote) {
      usageError(`用法錯誤：零提交雜務單 #${issueNum} 交件必須加上 --note "<做了什麼>"`);
    }
    const commentBody = [
      `🛠️ ${worker}`,
      '📦 交件（零提交）',
      '',
      trimmedNote,
    ].join('\n');
    postIssueComment(ctx, issueNum, commentBody);
    swapIssueLabels(ctx, issueNum, 'status:fixed', 'status:in-progress');
    await recordWorkerSubmit(ctx, { worker, issueNum, addedLines: 0 });
    console.log(`交件完成：#${issueNum}`);
    return 0;
  }

  const taskDir = getTaskDir(ctx, issueNum);
  const branchName = formatTaskBranch(ctx, issueNum);
  if (!fs.existsSync(taskDir)) {
    fail(`拒絕交件：找不到工作資料夾 ${taskDir}`);
  }

  const scope = parseValidatedScope(ctx.lib, issueNum, target.body, '拒絕交件');
  const affectedRepos = getAffectedRepoKeys(scope);
  const reposToPush: Array<{ repo: RuntimeRepo; wtPath: string; headSha: string }> = [];

  for (const repo of ctx.repos) {
    if (!affectedRepos.has(repo.key)) continue;
    const wtPath = path.join(taskDir, repo.name);
    if (!fs.existsSync(wtPath)) {
      fail(`拒絕交件：找不到受影響倉庫的工作資料夾 ${wtPath}`);
    }

    const branchRes = runGit(wtPath, ['rev-parse', '--abbrev-ref', 'HEAD']);
    if (!branchRes.ok || branchRes.stdout.trim() !== branchName) {
      fail(`拒絕交件：${repo.name}（${repo.key}）目前不在任務分支 ${branchName}`);
    }

    const statusRes = runGit(wtPath, ['-c', 'core.quotepath=false', 'status', '--porcelain', '-z', '-uall']);
    if (!statusRes.ok) {
      fail(`拒絕交件：檢查 ${repo.name} 工作區狀態失敗：${statusRes.stderr || statusRes.stdout}`);
    }
    const dirtyEntries = parseGitStatusPorcelainZ(statusRes.stdout);
    if (dirtyEntries.length > 0) {
      fail(
        `拒絕交件：${repo.name}（${repo.key}）工作資料夾有未提交改動：\n${dirtyEntries.map((e) => `- ${e.path}`).join('\n')}`,
      );
    }

    const baseRef = resolveBaseRef(wtPath);
    const aheadRes = runGit(wtPath, ['rev-list', '--count', `${baseRef}..HEAD`]);
    if (!aheadRes.ok) {
      fail(`拒絕交件：無法計算 ${repo.name} 相對於 ${baseRef} 的提交數：${aheadRes.stderr || aheadRes.stdout}`);
    }
    const aheadCount = Number(aheadRes.stdout.trim());
    if (aheadCount > 0) {
      const headRes = runGit(wtPath, ['rev-parse', 'HEAD']);
      if (!headRes.ok) {
        fail(`拒絕交件：無法取得 ${repo.name} 的 HEAD commit：${headRes.stderr || headRes.stdout}`);
      }
      reposToPush.push({ repo, wtPath, headSha: headRes.stdout.trim() });
    }
  }

  if (reposToPush.length === 0) {
    fail('拒絕交件：所有受影響倉庫都沒有比 origin/main 多出的提交');
  }

  const summary = verifyIssueScopeAndLines(ctx, {
    issueNum,
    targetBody: target.body,
    scope,
    branchName,
    taskDir,
    failPrefix: '拒絕交件',
  });

  const precheck = runSubmitPrecheck({
    ctx,
    scope,
    affectedRepos,
    issueBody: target.body,
    summary,
  });
  if (!precheck.passed) {
    fail(precheck.errorMessage);
  }

  for (const item of reposToPush) {
    const pushRes = runGit(item.wtPath, ['push', 'origin', branchName]);
    if (!pushRes.ok) {
      fail(`拒絕交件：推送 ${item.repo.name}（${item.repo.key}）分支 ${branchName} 失敗：${pushRes.stderr || pushRes.stdout}`);
    }
  }

  const commentLines = [
    `🛠️ ${worker}`,
    '📦 交件',
    '',
    ...reposToPush.map((item) => `- ${item.repo.key}：${branchName} @ ${item.headSha}`),
    '',
    `業務程式新增：${summary.lineCheck.totalAdded}／${summary.lineCheck.limit} 行`,
    precheck.commentLine,
  ];
  if (note && note.trim()) {
    commentLines.push('', note.trim());
  }
  postIssueComment(ctx, issueNum, commentLines.join('\n'));
  swapIssueLabels(ctx, issueNum, 'status:fixed', 'status:in-progress');
  await recordWorkerSubmit(ctx, {
    worker,
    issueNum,
    addedLines: summary.lineCheck.totalAdded,
  });

  console.log(`交件完成：#${issueNum}`);
  return 0;
}

function restoreAutoGeneratedFiles(autoFilesToRestore: readonly AutoGeneratedFileItem[]): void {
  const byWt = new Map<string, AutoGeneratedFileItem[]>();
  for (const item of autoFilesToRestore) {
    let list = byWt.get(item.wtPath);
    if (!list) {
      list = [];
      byWt.set(item.wtPath, list);
    }
    list.push(item);
  }

  for (const [wtPath, items] of byWt.entries()) {
    const trackedToCheckout: string[] = [];
    const stagedAdded: string[] = [];
    const untracked: string[] = [];
    for (const item of items) {
      if (item.xy === '??') untracked.push(item.file);
      else if (item.xy[0] === 'A') stagedAdded.push(item.file);
      else trackedToCheckout.push(item.file);
    }

    if (stagedAdded.length > 0) {
      const resetRes = runGit(wtPath, ['reset', '-q', '--', ...stagedAdded]);
      if (!resetRes.ok) fail(`還原共用產生檔失敗：${resetRes.stderr || resetRes.stdout}`);
      untracked.push(...stagedAdded);
    }
    if (trackedToCheckout.length > 0) {
      const coRes = runGit(wtPath, ['checkout', '--', ...trackedToCheckout]);
      if (!coRes.ok) fail(`還原共用產生檔失敗：${coRes.stderr || coRes.stdout}`);
    }
    for (const relPath of untracked) {
      fs.rmSync(path.join(wtPath, relPath), { force: true });
    }
    console.log(`已還原共用產生檔：${items.map((x) => `${x.repo.key}:${x.file}`).join('、')}`);
  }
}

export async function cmdFinish(
  ctx: TaskContext,
  { issueNum, dryRun = false }: Pick<IssueCommandArgs, 'issueNum'> & { dryRun?: boolean },
): Promise<number> {
  const taskDir = getTaskDir(ctx, issueNum);
  const branchName = formatTaskBranch(ctx, issueNum);

  if (!fs.existsSync(taskDir)) {
    fail(`拒絕收工：找不到工作資料夾 ${taskDir}`);
  }

  const sharedEntries = parseSharedGeneratedEntries(ctx.config);
  const problems: string[] = [];
  const remoteBranchesToDelete: Array<{ repo: RuntimeRepo; mainRepoPath: string }> = [];
  const autoFilesToRestore: AutoGeneratedFileItem[] = [];

  for (const repo of ctx.repos) {
    const wtPath = path.join(taskDir, repo.name);
    if (!fs.existsSync(wtPath)) continue;

    const hasLocalBranch = runGit(repo.mainRepoPath, [
      'rev-parse',
      '--verify',
      '-q',
      `refs/heads/${branchName}`,
    ]).ok;

    if (hasLocalBranch) {
      const fetchRes = runGit(repo.mainRepoPath, ['fetch', '--prune', 'origin']);
      if (!fetchRes.ok) {
        console.warn(
          `提示：${repo.name} 執行 git fetch 失敗，將以本機現有狀態判斷合併狀態（${fetchRes.stderr || fetchRes.stdout}）`,
        );
      }
    }

    const statusRes = runGit(wtPath, ['-c', 'core.quotepath=false', 'status', '--porcelain', '-z', '-uall']);
    if (!statusRes.ok) {
      problems.push(`${repo.name}（${repo.key}）檢查工作區狀態失敗：${statusRes.stderr || statusRes.stdout}`);
    } else {
      for (const entry of parseGitStatusPorcelainZ(statusRes.stdout)) {
        if (isSharedGeneratedFile(ctx.lib, sharedEntries, repo.key, entry.path)) {
          autoFilesToRestore.push({ wtPath, repo, file: entry.path, xy: entry.xy });
        } else {
          problems.push(`${repo.name}（${repo.key}）有未提交修改：${entry.path}`);
        }
      }
    }

    const baseRef = resolveBaseRef(repo.mainRepoPath);
    const mergedHead = runGit(wtPath, ['merge-base', '--is-ancestor', 'HEAD', baseRef]).ok;
    const mergedBranch = hasLocalBranch
      ? runGit(repo.mainRepoPath, ['merge-base', '--is-ancestor', `refs/heads/${branchName}`, baseRef]).ok
      : true;

    if (!mergedHead || !mergedBranch) {
      problems.push(`${repo.name}（${repo.key}）的分支 ${branchName} 尚未合併進 ${baseRef}`);
    }

    if (hasLocalBranch) {
      const hasRemoteBranch = runGit(repo.mainRepoPath, [
        'rev-parse',
        '--verify',
        '-q',
        `refs/remotes/origin/${branchName}`,
      ]).ok;
      if (hasRemoteBranch) {
        remoteBranchesToDelete.push({ repo, mainRepoPath: repo.mainRepoPath });
      }
    }
  }

  if (problems.length > 0) {
    fail(`拒絕收工：\n${problems.map((p) => `- ${p}`).join('\n')}`);
  }

  if (dryRun) {
    if (autoFilesToRestore.length > 0) {
      console.log(`[dry-run] 會還原共用產生檔：${autoFilesToRestore.map((x) => `${x.repo.key}:${x.file}`).join('、')}`);
    }
    console.log(`[dry-run] 檢查通過，預計刪除工作資料夾：${taskDir}`);
    if (remoteBranchesToDelete.length > 0) {
      console.log('[dry-run] 會刪除的遠端分支：');
      for (const { repo } of remoteBranchesToDelete) {
        console.log(`- ${repo.name} (${repo.key}): ${branchName}`);
      }
    } else {
      console.log('[dry-run] 會刪除的遠端分支：（無）');
    }
    return 0;
  }

  if (autoFilesToRestore.length > 0) {
    restoreAutoGeneratedFiles(autoFilesToRestore);
  }

  for (const repo of ctx.repos) {
    const wtPath = path.join(taskDir, repo.name);
    if (fs.existsSync(wtPath)) {
      const rmRes = runGit(repo.mainRepoPath, ['worktree', 'remove', '--force', wtPath]);
      if (!rmRes.ok) {
        fail(`移除 ${repo.name} worktree 失敗：${rmRes.stderr || rmRes.stdout}`);
      }
    }
    const hasLocalBranch = runGit(repo.mainRepoPath, [
      'rev-parse',
      '--verify',
      '-q',
      `refs/heads/${branchName}`,
    ]).ok;
    if (hasLocalBranch) {
      runGit(repo.mainRepoPath, ['branch', '-D', branchName]);
    }
  }

  fs.rmSync(taskDir, { recursive: true, force: true });
  await releaseTicketFromWorkers(ctx, issueNum);

  const remoteDeleteFailures: Array<{ repoName: string; mainRepoPath: string; detail: string }> = [];
  for (const { repo, mainRepoPath } of remoteBranchesToDelete) {
    const delRes = runGit(mainRepoPath, ['push', 'origin', '--delete', branchName]);
    if (!delRes.ok) {
      remoteDeleteFailures.push({
        repoName: repo.name,
        mainRepoPath,
        detail: delRes.stderr || delRes.stdout || '未知錯誤',
      });
    }
  }

  if (remoteDeleteFailures.length > 0) {
    console.warn('收工警告：本機工作資料夾與分支已清理，但以下遠端分支刪除失敗，請手動刪除：');
    for (const f of remoteDeleteFailures) {
      console.warn(
        `- ${f.repoName}（分支 ${branchName}）：${f.detail}（可執行：git -C ${f.mainRepoPath} push origin --delete ${branchName}）`,
      );
    }
    return 1;
  }

  console.log(`收工完成：已清理 ${taskDir}`);
  return 0;
}
